import PDFDocument from 'pdfkit';

export const generatePdf = async (data)=>{
    return new Promise((resolve,reject)=>{
        const doc = new PDFDocument({
            size: 'A4',
            margin: 50,
            info:{
                Author: 'Cortex',
                Title: data.title,
                Creator:"Cortex"
            }
        });
        const chunks = []

        doc.on("data", (chunk) => chunks.push(chunk));
        doc.on("end", () => resolve(Buffer.concat(chunks)));
        doc.on("error", reject);

        doc
        .fontSize(28)
        .text(data.title, { align: 'center' })
        .fillColor("#111827")

        if(data.subtitle){
            doc.moveDown(0.5)
        }
        //subtitle

        doc
        .fontSize(12)
        .text(data.subtitle, { align: 'center' })
        .fillColor("#6B7280")

        doc.moveDown(2)
        

        data?.sections?.forEach(s =>{
            doc
            .fontSize(12)
            .text(s.heading)
            .fillColor("#111827")

            doc.moveDown(0.5)

            s?.points?.forEach((p)=>{
                doc
                .fontSize(12)
                .text("• "+p,{
                    lineGap:5
                })
                .fillColor("#374151")
            })
            doc.moveDown()

        })

        doc.moveDown()

            doc
            .fontSize(10)
            .text("Generated by cortex AI",{
                align: 'center'
            })
            .fillColor("#111827")


            doc.end()

    })

}